CREATE OR REPLACE VIEW V_COVER_PRODUCT AS
SELECT p.PRODUCT_CODE, p.NAME AS PRODUCT_NAME, c.COVER_ID, c.DESCRIPTION, c.INSR_LIMIT, c.COPAY_PCT,
       ROUND(c.INSR_LIMIT * (100 - NVL(c.COPAY_PCT, 0)) / 100, 2) AS NET_LIMIT
FROM CFG_PRODUCT p JOIN CFG_COVER c ON c.PRODUCT_CODE = p.PRODUCT_CODE;
